function fig = new_figure(w_in, h_in)
%NEW_FIGURE  White figure with an exact physical size in inches (for print).
fig = figure('Color', 'w', 'Units', 'inches', 'Position', [1 1 w_in h_in], ...
    'PaperUnits', 'inches', 'PaperSize', [w_in h_in], ...
    'PaperPosition', [0 0 w_in h_in], 'PaperPositionMode', 'manual', ...
    'InvertHardcopy', 'off');
end
